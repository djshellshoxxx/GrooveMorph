#!/usr/bin/env python3
"""Generates docs/specs/PARAMETER-TABLE.md from createParameterLayout() in src/PluginProcessor.cpp.

Usage (from the repository root):  python3 tools/gen_parameter_table.py          # rewrite the table
                                   python3 tools/gen_parameter_table.py --check  # exit 1 when the file is stale

The table is the host-visible parameter order. IDs are append-only: a new parameter must be added at the end of
createParameterLayout() and the table regenerated. --check also fails when an existing row moved or changed id.
The per-operation trim parameters are expanded from the loop in createParameterLayout() using
OperationTrims.cpp (names) and OperationParams.h (operation count).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROC = (ROOT / "src/PluginProcessor.cpp").read_text()
HDR = (ROOT / "src/PluginProcessor.h").read_text()
TRIMS = (ROOT / "src/core/control/OperationTrims.cpp").read_text()
OPS = (ROOT / "src/core/OperationParams.h").read_text()
OUT = ROOT / "docs/specs/PARAMETER-TABLE.md"

ids = dict(re.findall(r'static constexpr const char\* (\w+Id) = "(\w+)";', HDR))
body = PROC[PROC.index("GrooveMorphAudioProcessor::createParameterLayout()"):]
body = body[:body.index("return layout;")]

op_block = re.search(r"enum class OperationType[^{]*\{(.*?)Count", OPS, re.S).group(1)
op_count = len([l for l in op_block.split("\n") if re.match(r"\s*\w+,", l)])
op_names = re.findall(r'"([^"]+)"', re.search(r"operationNameTable\[\] = \{(.*?)\};", TRIMS, re.S).group(1))
kind_suffix = re.findall(r'"([^"]+)"', re.search(r"kindSuffix\[\] = \{(.*?)\};", TRIMS, re.S).group(1))
kind_id = re.findall(r'"([^"]+)"', re.search(r"kindId\[\] = \{(.*?)\};", TRIMS, re.S).group(1))


def clean(text):
    return re.sub(r"(\d)f\b", r"\1", re.sub(r"\s+", " ", text)).strip()


def describe(kind, args):
    """args: text after the name string literal, up to the closing parenthesis."""
    args = clean(args)
    if kind == "Float":
        m = re.search(r"NormalisableRange<float>\{([^}]*)\}", args)
        rng = m.group(1) if m else args
        default = args.rsplit(",", 1)[-1].strip()
        return "float", clean(rng), default
    if kind == "Int":
        parts = [p.strip() for p in args.split(",")]
        return "int", f"{parts[0]}..{parts[1]}", parts[2]
    if kind == "Bool":
        return "bool", "off/on", args.split(",")[-1].strip().rstrip(")")
    m = re.search(r"StringArray\{([^}]*)\}", args)
    choices = [c.strip().strip('"') for c in m.group(1).split('",')] if m else []
    choices = [c.strip().strip('"') for c in (m.group(1) if m else "").split(",")]
    default = args.rsplit(",", 1)[-1].strip()
    return "choice", " / ".join(choices), default


rows = []
# Statements outside the per-operation loop, in order. The loop is expanded at its position.
loop_start = body.index("for (std::size_t op = 0; op < core::operationCount; ++op)")
loop_end = body.index("// N05 Chaos macro")
before, after = body[:loop_start], body[loop_end:]


def scan(text):
    out = []
    for m in re.finditer(r"layout\.add\(std::make_unique<juce::AudioParameter(Float|Int|Bool|Choice)>\(\s*"
                         r"juce::ParameterID\{(\w+), 1\},\s*(\"[^\"]*\")\s*,(.*?)\)\);", text, re.S):
        kind, const, name, rest = m.groups()
        t, rng, default = describe(kind, rest)
        out.append((ids[const], name.strip('"'), t, rng, default))
    for m in re.finditer(r"layout\.add\(std::make_unique<juce::AudioParameterBool>\(\s*juce::ParameterID\{(\w+), 1\},\s*(\"[^\"]*\"),\s*(\w+)\)\);", text):
        pass  # bool parameters are matched by the generic pattern above
    return out


rows += scan(before)
trim_defaults = {"Enable": ("choice", "Scene / Off / On", "0 (Scene)"),
                 "Depth": ("float", "0..1", "1.0"),
                 "Slice": ("float", "0.25..4 (1 at mid travel)", "1.0")}
for op in range(op_count):
    for kid, suffix in zip(kind_id, kind_suffix):
        t, rng, default = trim_defaults[kid]
        name = (op_names[op] if op < len(op_names) else f"Effect {op + 1}") + ": " + suffix
        rows.append((f"op{op}{kid}", name, t, rng, default))
rows += scan(after)

ids_seen = [r[0] for r in rows]
assert len(ids_seen) == len(set(ids_seen)), "duplicate parameter id"

lines = [
    "# Host parameter table",
    "",
    "Generated by `python3 tools/gen_parameter_table.py` from `createParameterLayout()` in `src/PluginProcessor.cpp`. Do not edit by hand.",
    "All parameters use `ParameterID` version hint 1. The order below is the host-visible order and is append-only:",
    "never reorder, rename, retype, change the default of, or lengthen the choice list of an existing row. New parameters go at the end.",
    "A saved state that lacks a row restores it to its default (`setStateInformation`). The `op<N>...` trims are host-automation",
    "only (no editor control); every other row has an editor control (full view and, for the macros, Easy mode).",
    "",
    "| # | ID | Name | Type | Range / choices | Default |",
    "|---|---|---|---|---|---|",
]
for i, (pid, name, t, rng, default) in enumerate(rows):
    lines.append(f"| {i} | `{pid}` | {name} | {t} | {rng} | {default} |")
lines.append("")
lines.append(f"Total: {len(rows)} parameters ({op_count} operations x 3 trims = {op_count * 3} of them).")
text = "\n".join(lines) + "\n"

if "--check" in sys.argv:
    old = OUT.read_text() if OUT.exists() else ""
    if old != text:
        sys.stderr.write("docs/specs/PARAMETER-TABLE.md is stale: run python3 tools/gen_parameter_table.py\n")
        sys.exit(1)
    sys.exit(0)
OUT.write_text(text)
print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} parameters)")
